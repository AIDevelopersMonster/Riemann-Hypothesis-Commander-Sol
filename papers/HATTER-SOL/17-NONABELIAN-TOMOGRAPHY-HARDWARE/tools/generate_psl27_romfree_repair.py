#!/usr/bin/env python3
"""Generate H17-06 ROM-free one-erasure repair RTL for the robust8 code.

The module receives the 24-bit eight-class signature plus a known erased
coordinate index.  It never reads the erased 3-bit coordinate.  Instead it uses
an exact depth-optimal decision tree on surviving class coordinates to:

  * reject realizable non-generating PSL(2,7) signature states;
  * reconstruct the missing class for generating states;
  * emit the complete 24-bit signature as a canonical orbit fingerprint.

No 114-entry orbit ROM is used.  The tree is generated by exact dynamic
programming with objective (minimum worst-case query depth, then minimum number
of internal decision nodes).
"""
from __future__ import annotations

import argparse
from functools import lru_cache
from pathlib import Path

from generate_psl27_golden_model import CLASS_CODE
from generate_psl27_robust8 import PROBES, verify

GEN, NON = verify()


def coded(sig):
    return tuple(CLASS_CODE[x] for x in sig)


GENC = [coded(s) for s in GEN]
NONC = [coded(s) for s in NON]


def build_problem(erased: int):
    feats = tuple(i for i in range(8) if i != erased)
    rows = {}
    for sig in GENC:
        p = tuple(sig[i] for i in feats)
        lab = ("G", sig[erased])
        old = rows.get(p)
        assert old is None or old == lab
        rows[p] = lab
    for sig in NONC:
        p = tuple(sig[i] for i in feats)
        lab = ("N",)
        old = rows.get(p)
        assert old is None or old == lab
        rows[p] = lab
    patterns = tuple(rows.keys())
    labels = tuple(rows[p] for p in patterns)
    local = {f: feats.index(f) for f in feats}
    return feats, patterns, labels, local


def solve_tree(erased: int):
    feats, patterns, labels, local = build_problem(erased)

    @lru_cache(None)
    def solve(states, remaining):
        labs = {labels[s] for s in states}
        if len(labs) == 1:
            return (0, 0, None)
        best = None
        for f in remaining:
            li = local[f]
            parts = {}
            for s in states:
                parts.setdefault(patterns[s][li], []).append(s)
            if len(parts) <= 1:
                continue
            nr = tuple(x for x in remaining if x != f)
            child = [solve(tuple(ss), nr) for ss in parts.values()]
            if any(r[0] >= 999 for r in child):
                continue
            cand = (1 + max(r[0] for r in child), 1 + sum(r[1] for r in child), f)
            if best is None or cand[:2] < best[:2]:
                best = cand
        return best if best is not None else (999, 999, None)

    root_states = tuple(range(len(patterns)))
    depth, nodes, root = solve(root_states, feats)
    assert depth == 4

    def materialize(states, remaining):
        labs = {labels[s] for s in states}
        if len(labs) == 1:
            return ("leaf", next(iter(labs)))
        _, _, f = solve(tuple(states), tuple(remaining))
        li = local[f]
        parts = {}
        for s in states:
            parts.setdefault(patterns[s][li], []).append(s)
        nr = tuple(x for x in remaining if x != f)
        return ("node", f, {v: materialize(tuple(ss), nr) for v, ss in sorted(parts.items())})

    return materialize(root_states, feats), depth, nodes, len(patterns), root


def coord_slice(i: int) -> tuple[int, int]:
    hi = 23 - 3 * i
    return hi, hi - 2


def emit_tree(lines, tree, erased: int, indent: str):
    kind = tree[0]
    if kind == "leaf":
        label = tree[1]
        if label[0] == "N":
            lines.append(indent + "valid = 1'b0;")
            return
        missing = label[1]
        hi, lo = coord_slice(erased)
        lines.append(indent + "valid = 1'b1;")
        lines.append(indent + f"repaired_signature[{hi}:{lo}] = 3'd{missing};")
        return
    _, f, branches = tree
    hi, lo = coord_slice(f)
    lines.append(indent + f"case (signature[{hi}:{lo}]) // {PROBES[f]}")
    for value, child in branches.items():
        lines.append(indent + f"  3'd{value}: begin")
        emit_tree(lines, child, erased, indent + "    ")
        lines.append(indent + "  end")
    lines.append(indent + "  default: valid = 1'b0;")
    lines.append(indent + "endcase")


def emit_repair(path: Path):
    solved = [solve_tree(e) for e in range(8)]
    lines = [
        "// Auto-generated H17-06 ROM-free one-erasure repair decoder.",
        "// The erased coordinate is never queried by any decision tree.",
        "module psl27_robust8_repair(",
        "    input  logic [23:0] signature,",
        "    input  logic [2:0]  erased_idx,",
        "    output logic        valid,",
        "    output logic [23:0] repaired_signature",
        ");",
        "always @* begin",
        "  valid = 1'b0;",
        "  repaired_signature = signature;",
        "  case (erased_idx)",
    ]
    for e, (tree, depth, nodes, count, root) in enumerate(solved):
        lines.append(f"    3'd{e}: begin // erase {PROBES[e]}: depth={depth}, nodes={nodes}, states={count}, root={PROBES[root]}")
        emit_tree(lines, tree, e, "      ")
        lines.append("    end")
    lines += [
        "    default: begin valid = 1'b0; repaired_signature = signature; end",
        "  endcase",
        "end",
        "endmodule",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    return solved


def pack_sig(sig):
    v = 0
    for c in sig:
        v = (v << 3) | c
    return v


def corrupt(sig, erased):
    x = list(sig)
    x[erased] = 7
    return tuple(x)


def emit_tb(path: Path):
    lines = [
        "`timescale 1ns/1ps",
        "module tb_psl27_robust8_repair;",
        "logic [23:0] signature; logic [2:0] erased_idx; logic valid; logic [23:0] repaired_signature;",
        "psl27_robust8_repair dut(.signature(signature),.erased_idx(erased_idx),.valid(valid),.repaired_signature(repaired_signature));",
        "task automatic check_g(input logic [23:0] damaged,input logic [2:0] e,input logic [23:0] expected); begin",
        "  signature=damaged; erased_idx=e; #1; if(!valid || repaired_signature!==expected) $fatal(1);",
        "end endtask",
        "task automatic check_n(input logic [23:0] damaged,input logic [2:0] e); begin",
        "  signature=damaged; erased_idx=e; #1; if(valid) $fatal(1);",
        "end endtask",
        "initial begin",
    ]
    for sig in GENC:
        expected = pack_sig(sig)
        for e in range(8):
            lines.append(f"  check_g(24'h{pack_sig(corrupt(sig,e)):06x},3'd{e},24'h{expected:06x});")
    for sig in NONC:
        for e in range(8):
            lines.append(f"  check_n(24'h{pack_sig(corrupt(sig,e)):06x},3'd{e});")
    lines += [
        '$display("PASS: ROM-free repair checked 114*8 generating and 66*8 non-generating erasure states");',
        "$finish; end",
        "endmodule",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def emit_core(path: Path):
    path.write_text("""// H17-06 ROM-free robust fingerprint core.
module psl27_robust8_romfree_core(
    input  logic [23:0] A,
    input  logic [23:0] B,
    input  logic [2:0]  erased_idx,
    output logic        input_valid,
    output logic        fingerprint_valid,
    output logic [23:0] raw_signature,
    output logic [23:0] orbit_fingerprint
);
logic repair_valid;
psl27_robust8_engine u_eng(.A(A),.B(B),.valid(input_valid),.signature(raw_signature));
psl27_robust8_repair u_rep(.signature(raw_signature),.erased_idx(erased_idx),.valid(repair_valid),.repaired_signature(orbit_fingerprint));
assign fingerprint_valid = input_valid & repair_valid;
endmodule
""", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default="generated_romfree")
    args = ap.parse_args()
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    solved = emit_repair(out / "psl27_robust8_repair.sv")
    emit_tb(out / "tb_psl27_robust8_repair.sv")
    emit_core(out / "psl27_robust8_romfree_core.sv")
    print("PASS: emitted ROM-free H17-06 repair processor")
    print("worst-case class-query depth =", max(x[1] for x in solved))
    print("decision nodes by erasure =", [x[2] for x in solved])
    print("total depth-optimal internal nodes =", sum(x[2] for x in solved))
    print("orbit fingerprint bits = 24; orbit ROM entries = 0")


if __name__ == "__main__":
    main()
